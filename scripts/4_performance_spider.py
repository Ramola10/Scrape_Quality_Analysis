"""Scrapy spider for a controlled local-server benchmark.

This file is invoked by 4_run_performance.py via `python -m scrapy runspider`.
Only crawl localhost endpoints generated by that runner.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from urllib.parse import urlsplit

import scrapy


class PerformanceSpider(scrapy.Spider):
    name = "local_performance_benchmark"

    def __init__(self, base_url: str, pages: str = "200", result_file: str = "", **kwargs):
        super().__init__(**kwargs)
        self.base_url = base_url.rstrip("/")
        host = urlsplit(self.base_url).hostname
        if host not in {"127.0.0.1", "localhost", "::1"}:
            raise ValueError("The performance benchmark must only target localhost")
        self.pages = int(pages)
        if self.pages <= 0:
            raise ValueError("pages must be positive")
        if not result_file:
            raise ValueError("result_file argument is required")
        self.result_file = Path(result_file)
        self.latencies = []
        self.successful_pages = 0
        self.unexpected_pages = 0

    async def start(self):
        for i in range(self.pages):
            yield scrapy.Request(
                f"{self.base_url}/page/{i}",
                callback=self.parse,
                errback=self.on_error,
                dont_filter=True,
            )

    def parse(self, response):
        if response.status == 200:
            self.successful_pages += 1
        else:
            self.unexpected_pages += 1
        latency = response.meta.get("download_latency")
        if isinstance(latency, (int, float)) and math.isfinite(latency):
            self.latencies.append(float(latency))
        yield {"url": response.url, "status": response.status}

    def on_error(self, failure):
        self.unexpected_pages += 1

    def closed(self, reason):
        # Scrapy's download_latency is measured until the HTTP response headers;
        # it does not include full response-body transfer or callback processing.
        ordered = sorted(self.latencies)
        p95 = ordered[max(0, math.ceil(0.95 * len(ordered)) - 1)] if ordered else None
        stats = self.crawler.stats.get_stats()
        summary = {
            "reason": reason,
            "requested_pages": self.pages,
            "successful_pages": self.successful_pages,
            "unexpected_pages": self.unexpected_pages,
            "item_scraped_count": stats.get("item_scraped_count", 0),
            "downloader_response_count": stats.get("downloader/response_count", 0),
            "p95_download_latency_s": p95,
            "latency_sample_count": len(ordered),
        }
        self.result_file.parent.mkdir(parents=True, exist_ok=True)
        self.result_file.write_text(json.dumps(summary, indent=2), encoding="utf-8")
